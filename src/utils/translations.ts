/**
 * Normaliza o nome de um idioma digitado pelo usuário para um código de idioma suportado (pt, en, fr, es, de, it, ja).
 * Caso não corresponda a nenhum, retorna 'en' (inglês) por padrão para termos uma interface coerente.
 */
export function normalizeLanguage(langName: string): AppLanguage {
  if (!langName) return "en";
  const name = langName.toLowerCase().trim();

  if (name.includes("portug") || name === "pt" || name === "br") {
    return "pt";
  }
  if (name.includes("ingl") || name.includes("engl") || name === "en") {
    return "en";
  }
  if (name.includes("franc") || name.includes("franç") || name.includes("fren") || name === "fr") {
    return "fr";
  }
  if (name.includes("espan") || name.includes("españ") || name.includes("span") || name === "es") {
    return "es";
  }
  if (name.includes("alem") || name.includes("germ") || name.includes("deut") || name === "de") {
    return "de";
  }
  if (name.includes("ital") || name === "it") {
    return "it";
  }
  if (name.includes("japon") || name.includes("nihon") || name.includes("japan") || name === "ja" || name === "jp") {
    return "ja";
  }

  // Se for qualquer outro idioma, retornamos "en" como fallback razoável
  return "en";
}
